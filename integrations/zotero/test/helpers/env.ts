/** The engine host of the tests: node:fs, a temp dir, and the fake Sqlite.sys.mjs. */
export function nodeHost(dir: string, sqlite: FakeSqlite = fakeSqlite()): EngineHost & { fake: FakeSqlite } {
  let n = 0;
  return {
    fake: sqlite,
    sqlite: () => sqlite,
    readFile: (p) => readFile(p),
    async readFileHead(p, length) {
      const fh = await open(p, 'r');
      try {
        const buf = Buffer.alloc(length);
        const { bytesRead } = await fh.read(buf, 0, length, 0);
        return buf.subarray(0, bytesRead);
      } finally {
        await fh.close();
      }
    },
    writeFile: (p, d) => writeFile(p, d),
    remove: (p) => rm(p, { force: true }),
    tempPath: (prefix) => join(dir, `${prefix}${n++}.sqlite`),
    decompressionStream: () => globalThis.DecompressionStream as never,
  };
}

