export interface FtlMessage {
  value: string | null;
  attributes: Record<string, string>;
}

/** A small parser for the subset of Fluent the plugin uses (single-line values and attributes). */
export function parseFtl(text: string): Map<string, FtlMessage> {
  const out = new Map<string, FtlMessage>();
  let current: FtlMessage | null = null;
  for (const line of text.split('\n')) {
    if (!line.trim() || line.startsWith('#')) {
      if (!line.trim()) current = null;
      continue;
    }
    const msg = /^([a-z][a-z0-9-]*)\s*=\s*(.*)$/.exec(line);
    if (msg) {
      current = { value: (msg[2] as string).trim() || null, attributes: {} };
      if (out.has(msg[1] as string)) throw new Error(`duplicate id ${msg[1]}`);
      out.set(msg[1] as string, current);
      continue;
    }
    const attr = /^\s+\.([a-z][a-z0-9-]*)\s*=\s*(.*)$/.exec(line);
    if (attr && current) {
      current.attributes[attr[1] as string] = (attr[2] as string).trim();
      continue;
    }
    throw new Error(`unparsed FTL line: ${line}`);
  }
  return out;
}

export function ftl(locale: 'en-US' | 'es-ES'): Map<string, FtlMessage> {
  return parseFtl(readFileSync(join(ROOT, 'addon', 'locale', locale, 'spdf-zotero.ftl'), 'utf8'));
}

/** A `Translate` over an FTL file; unknown ids throw, so a missing string fails the test. */
export function translator(locale: 'en-US' | 'es-ES' = 'en-US') {
  const messages = ftl(locale);
  return async (id: string, args: Record<string, string | number> = {}): Promise<string> => {
    const m = messages.get(id);
    if (!m || m.value === null) throw new Error(`missing Fluent string ${id}`);
    return m.value.replace(/\{\s*\$([a-z]+)\s*\}/g, (_, k: string) => {
      if (!(k in args)) throw new Error(`missing argument ${k} for ${id}`);
      return String(args[k]);
    });
  };
}
